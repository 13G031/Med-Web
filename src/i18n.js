export function translate(value, language) {
  return language === 'en' && typeof value === 'string' ? english[value] ?? value : value
}

export function localize(value, language) {
  if (language !== 'en' || value == null) return value
  if (typeof value === 'string') return translate(value, language)
  if (Array.isArray(value)) return value.map((item) => localize(item, language))
  if (typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, localize(item, language)]))
  }
  return value
}
